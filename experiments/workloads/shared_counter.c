/* Purpose-built native cache-line contention, not representative Cargo work.
 * Each reported unit is 100,000 completed atomic operations. mmap is confined
 * to a caller-owned 4 KiB temporary file; there is no memory-pressure injection.
 */
#define _POSIX_C_SOURCE 200809L
#include <stdatomic.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <fcntl.h>
#include <sys/mman.h>
#include <sys/stat.h>
#include <time.h>
#include <unistd.h>

static double clock_seconds(clockid_t which) {
    struct timespec ts;
    if (clock_gettime(which, &ts)) { perror("clock_gettime"); exit(2); }
    return ts.tv_sec + ts.tv_nsec / 1e9;
}
static void progress(unsigned long done, unsigned long total, const char *epoch) {
    printf("KYOTO_PROGRESS {\"completed\":%lu,\"total\":%lu,\"phase\":\"atomic-work\","
           "\"epoch\":\"%s\",\"reported_at\":%.9f}\n", done, total, epoch, clock_seconds(CLOCK_REALTIME));
    fflush(stdout);
}
int main(int argc, char **argv) {
    if (argc != 6) return 2;
    char *end;
    unsigned long units = strtoul(argv[2], &end, 10);
    if (*end || units < 1 || units > 20000000) return 2;
    unsigned long slot = strtoul(argv[3], &end, 10);
    if (*end || slot > 15) return 2;
    /* Epoch is generated by the parent, never arbitrary shell or JSON input. */
    for (const char *s=argv[5]; *s; ++s)
        if (!((*s>='0' && *s<='9') || (*s>='a' && *s<='f'))) return 2;
    if (strlen(argv[5]) != 32) return 2;
    int fd=open(argv[1], O_RDWR);
    if (fd<0) {perror("open"); return 2;}
    struct stat st;
    if (fstat(fd,&st) || st.st_size!=4096) {close(fd); return 2;}
    void *mapping=mmap(NULL,4096,PROT_READ|PROT_WRITE,MAP_SHARED,fd,0);
    close(fd);
    if (mapping==MAP_FAILED) {perror("mmap"); return 2;}
    _Atomic uint64_t *shared=(_Atomic uint64_t *)mapping;
    _Atomic uint64_t *private_line=(_Atomic uint64_t *)((char *)mapping+128*(slot+1));
    if (!atomic_is_lock_free(shared)) {munmap(mapping,4096); return 3;}
    double reported=clock_seconds(CLOCK_MONOTONIC);
    progress(0,units,argv[5]);
    for (unsigned long i=0; i<units; ++i) {
        _Atomic uint64_t *counter=access(argv[4],F_OK)==0 ? private_line : shared;
        for (unsigned j=0;j<100000;++j)
            atomic_fetch_add_explicit(counter,1,memory_order_relaxed);
        double now=clock_seconds(CLOCK_MONOTONIC);
        if (now-reported>=.2 || i+1==units) {progress(i+1,units,argv[5]); reported=now;}
    }
    munmap(mapping,4096);
    return 0;
}
